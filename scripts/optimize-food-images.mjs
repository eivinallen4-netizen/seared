/**
 * Turns the transparent source PNGs in assets-src/food/ into web-ready WebP files
 * in public/food/ and regenerates src/data/food-images.ts with their sizes.
 *
 *   node scripts/optimize-food-images.mjs
 *
 * To replace an image with real photography: drop a transparent PNG with the same
 * id into assets-src/food/ (e.g. plate-steak.png) and rerun this script.
 */
import sharp from "sharp";
import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const srcDir = path.join(root, "assets-src/food");
const outDir = path.join(root, "public/food");

export const IDS = [
  "hero-tray",
  "plate-steak", "plate-chicken", "plate-shrimp", "plate-salmon", "plate-lamb-chop", "plate-filet-mignon",
  "taco-chicken", "taco-steak", "taco-shrimp", "taco-lamb-chop", "taco-lobster-tail",
  "corn-loaded-cajun",
  "base-penne", "base-rice", "base-half-half",
  "protein-steak", "protein-chicken", "protein-shrimp", "protein-salmon",
  "protein-lamb-chop", "protein-filet-mignon", "protein-lobster-tail",
  "tray-empty",
];

// Ids listed here keep their full canvas (no crop to the visible food).
const NO_TRIM = new Set([]);

await mkdir(outDir, { recursive: true });
const files = new Set(await readdir(srcDir));
const entries = {};

for (const id of IDS) {
  if (!files.has(`${id}.png`)) {
    console.warn(`missing  ${id}.png`);
    entries[id] = null;
    continue;
  }
  const maxW = id === "hero-tray" ? 1600 : id.startsWith("protein-") ? 640 : 900;
  const src = sharp(path.join(srcDir, `${id}.png`)).ensureAlpha();
  const { data: raw, info: meta } = await src.clone().raw().toBuffer({ resolveWithObject: true });
  // Drop faint alpha haze left by background removal, then crop to the visible food.
  for (let i = 3; i < raw.length; i += 4) if (raw[i] < 14) raw[i] = 0;
  const cleaned = sharp(raw, { raw: { width: meta.width, height: meta.height, channels: 4 } });
  let trimmed;
  if (NO_TRIM.has(id)) {
    trimmed = await cleaned.png().toBuffer();
  } else {
    let [x0, y0, x1, y1] = [meta.width, meta.height, -1, -1];
    for (let y = 0; y < meta.height; y++)
      for (let x = 0; x < meta.width; x++)
        if (raw[(y * meta.width + x) * 4 + 3] > 40) {
          if (x < x0) x0 = x;
          if (x > x1) x1 = x;
          if (y < y0) y0 = y;
          if (y > y1) y1 = y;
        }
    trimmed = await cleaned
      .extract({ left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 })
      .png()
      .toBuffer();
  }
  const pad = NO_TRIM.has(id) ? 0 : 8;
  const { data, info } = await sharp(trimmed)
    .extend({ top: pad, bottom: pad, left: pad, right: pad, background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .resize({ width: maxW, withoutEnlargement: true })
    .webp({ quality: 82, alphaQuality: 90, effort: 6 })
    .toBuffer({ resolveWithObject: true });
  await writeFile(path.join(outDir, `${id}.webp`), data);
  entries[id] = { src: `/food/${id}.webp`, width: info.width, height: info.height };
  console.log(`ok       ${id}.webp  ${info.width}x${info.height}  ${(data.length / 1024).toFixed(0)} KB`);
}

const ts = `// AUTO-GENERATED by scripts/optimize-food-images.mjs — do not edit by hand.
// Representative AI-generated images; replace with real photography (see assets-src/README.md).

export type FoodImage = { src: string; width: number; height: number };

export const foodImages = ${JSON.stringify(entries, null, 2)} as const satisfies Record<string, FoodImage | null>;

export type FoodImageId = keyof typeof foodImages;
`;
await writeFile(path.join(root, "src/data/food-images.ts"), ts);
console.log("wrote src/data/food-images.ts");
